# -*- coding: utf-8 -*-
r"""Build the daily-verse app: bible_data.js (verse text) + data.js (your record).

Run:  py make_bible_data.py

bible_data.js  the whole World English Bible as compact JS. ~3.5 MB, synced
               once, never changes. Loaded with a <script> tag, which is the
               only read that works from a file:// page (fetch is blocked).
data.js        your record: which books you chose, verses/day, and every day
               you marked done. THIS is the file that syncs between laptop
               and phone. Only bible_server.py writes it; the phone asks the
               server to write it (see bible.html).

Both files live in this folder, which is inside your synced Songs share.
"""
import io
import json
import os
import re
import stat
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = r"C:\Users\young\AppData\Local\Temp\opencode\web_bible.json"
OUT_DB = os.path.join(HERE, "bible_data.js")
OUT_REC = os.path.join(HERE, "data.js")

# books that make good daily tasks: big enough to have real substance
DEFAULT_BOOKS = ["Psalms", "Proverbs", "Matthew"]
DEFAULT_PER_DAY = 2


def clean(s):
    """The source text carries odd spacing around punctuation; tidy it."""
    s = re.sub(r"\s+", " ", s or "").strip()
    s = s.replace(" ,", ",").replace(" .", ".").replace(" ;", ";")
    s = s.replace(" :", ":").replace(" (", " (").replace(" )", ")")
    s = re.sub(r"\(\s+", "(", s)
    s = re.sub(r"\s+\)", ")", s)
    # the source puts a space before curly apostrophes: "didn' t", "Yahweh ' s"
    s = re.sub(r"\s+(['\u2019])", r"\1", s)
    s = re.sub(r"(['\u2019])\s+", r"\1", s)
    # nested quote spacing: Pray like this: " ' Our Father ... ' "
    s = s.replace('"\u2018 ', '"\u2018').replace(' \u2019"', '\u2019"')
    # space right after an opening quote is always an artifact
    s = s.replace('\u2018 ', '\u2018')
    # a closing quote glued to the next word's first CAPITAL is an artifact;
    # possessives ("Yahweh's") are lowercase, so this never fires on those
    s = re.sub(r"\u2019(?=[A-Z])", "\u2019 ", s)
    return s


def build_db(books):
    out = []
    for b in books:
        name = b["name"]
        chs = []
        for ch in b["chapters"]:
            # verses are a flat list: element i is verse i+1
            vs = [clean(t) for t in ch]
            chs.append(vs)
        out.append([name, chs])
    return out


def main():
    if not os.path.exists(RAW):
        print("missing source text: %s" % RAW)
        print("download it first - see docstring")
        return 1
    books = json.load(io.open(RAW, encoding="utf-8"))
    db = build_db(books)

    nverses = sum(len(c) for _, chs in db for c in chs)
    js = ("/* Whole World English Bible, public domain. Generated by\n"
          "   make_bible_data.py - do not edit by hand. */\n"
          "window.VERSE_DB=" + json.dumps(db, ensure_ascii=False,
                                         separators=(",", ":")) + ";\n")
    with io.open(OUT_DB, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("bible_data.js  %7d KB  %d books, %d verses"
          % (len(js.encode("utf-8")) // 1024, len(db), nverses))

    # config.js: the address the phone posts to. The server serves a fresh
    # copy over http; this on-disk one is only used when the page is opened
    # as a plain file, so it may go stale if the laptop's IP changes - the
    # Settings tab lets you type the address by hand if that happens.
    try:
        import socket
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            s.connect(("8.8.8.8", 80))
            ip = s.getsockname()[0]
        finally:
            s.close()
    except OSError:
        ip = "127.0.0.1"
    cfg = ("window.APP_HOST=%s;\nwindow.APP_PORT=8395;\n"
           % json.dumps(ip))
    with io.open(os.path.join(HERE, "config.js"), "w", encoding="utf-8",
                 newline="\n") as f:
        f.write(cfg)
    print("config.js      laptop address %s:8395" % ip)

    # record file: only seed it if it does not exist, so re-running the
    # generator never wipes the user's history
    if not os.path.exists(OUT_REC):
        rec = {
            "v": 1,
            "settings": {
                "books": DEFAULT_BOOKS,
                "perDay": DEFAULT_PER_DAY,
                "updatedAt": 0,
            },
            "days": {},
        }
        js2 = ("/* Your daily-verse record. Written by bible_server.py.\n"
               "   Do not edit while the app is open. */\n"
               "window.RECORD=" + json.dumps(rec, ensure_ascii=False,
                                             separators=(",", ":")) + ";\n")
        with io.open(OUT_REC, "w", encoding="utf-8", newline="\n") as f:
            f.write(js2)
        print("data.js        created (fresh record)")
    else:
        try:
            os.chmod(OUT_REC, stat.S_IWRITE | stat.S_IREAD)
        except OSError:
            pass
        print("data.js        kept (already exists - history preserved)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
